// @vitest-environment node
import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { afterEach, expect, it } from "vitest";
import { parse } from "yaml";
import {
  collectMigrations,
  renderIndexFile,
} from "./generate-room-do-migrations.mjs";
import { buildPreviewBundle } from "./preview-bundle.mts";

const paths: string[] = [];
afterEach(() => {
  for (const path of paths.splice(0))
    rmSync(path, { recursive: true, force: true });
});
function git(root: string, args: string[]): string {
  return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
}
function fixture(): { root: string; sha: string } {
  const root = mkdtempSync(resolve(tmpdir(), "preview-build-source-"));
  paths.push(root);
  for (const child of [
    "workers/migrations",
    "workers/room-do-migrations",
    "node_modules/wrangler/bin",
  ])
    mkdirSync(resolve(root, child), { recursive: true });
  writeFileSync(
    resolve(root, ".gitignore"),
    "node_modules/\n.preview-bundle/\nworkers/room-do-migrations/index.ts\nnext-env.d.ts\n",
  );
  writeFileSync(resolve(root, "wrangler.preview.jsonc"), "{}");
  writeFileSync(
    resolve(root, "workers/migrations/0001_example.sql"),
    "CREATE TABLE example(id TEXT);",
  );
  writeFileSync(
    resolve(root, "workers/room-do-migrations/20261011000000-example.sql"),
    "CREATE TABLE room_example(id TEXT);",
  );
  writeFileSync(
    resolve(root, "workers/room-do-migrations/index.ts"),
    renderIndexFile(
      collectMigrations(
        { readdirSync, readFileSync },
        resolve(root, "workers/room-do-migrations"),
      ),
    ),
  );
  // 外部操作を持たない小さなcompilerで、bundle作成まで進んだことを観測する。
  writeFileSync(
    resolve(root, "node_modules/wrangler/bin/wrangler.js"),
    "const {writeFileSync}=require('node:fs');const {resolve}=require('node:path');writeFileSync(resolve(process.cwd(),'.preview-bundle/preview-app-worker.js'),\"export default {fetch(){return new Response('test')}}\");",
  );
  git(root, ["init", "--initial-branch=pr", "--quiet"]);
  git(root, ["config", "user.email", "preview-test@example.test"]);
  git(root, ["config", "user.name", "Preview Test"]);
  git(root, ["add", "."]);
  git(root, ["commit", "--quiet", "-m", "PR head"]);
  return { root, sha: git(root, ["rev-parse", "HEAD"]) };
}

it("merge treeをPR headとしてbuildできない", async () => {
  const { root, sha } = fixture();
  git(root, ["checkout", "--quiet", "-b", "base"]);
  writeFileSync(resolve(root, "workers/migrations/0002_base.sql"), "SELECT 1;");
  git(root, ["add", "."]);
  git(root, ["commit", "--quiet", "-m", "Base migration"]);
  git(root, ["checkout", "--quiet", "pr"]);
  git(root, ["merge", "--quiet", "--no-ff", "--no-edit", "base"]);
  await expect(buildPreviewBundle(root, sha)).rejects.toThrow(
    /head|commit|コミット/,
  );
});
it("commit後にSQLを書き換えた作業treeをbuildできない", async () => {
  const { root, sha } = fixture();
  writeFileSync(
    resolve(root, "workers/migrations/0001_example.sql"),
    "SELECT 1;",
  );
  await expect(buildPreviewBundle(root, sha)).rejects.toThrow(
    /ソース|source|コミット/,
  );
});
it("古いRoomDO生成物を同梱するbuildを拒否する", async () => {
  const { root, sha } = fixture();
  writeFileSync(
    resolve(root, "workers/room-do-migrations/index.ts"),
    "old sql",
  );
  await expect(buildPreviewBundle(root, sha)).rejects.toThrow(/RoomDO/);
});
it("生成されたnext-env.d.tsはcommitされたソースと区別してbuildできる", async () => {
  const { root, sha } = fixture();
  writeFileSync(resolve(root, "next-env.d.ts"), "// Generated by Next");
  await expect(buildPreviewBundle(root, sha)).resolves.toBeUndefined();
});
it("公開するCI buildはPR headをcheckoutし、RoomDO SQLもartifactへ含める", () => {
  const workflow = parse(
    readFileSync(
      new URL("../.github/workflows/ci.yml", import.meta.url),
      "utf8",
    ),
  );
  const steps = workflow.jobs.build.steps;
  expect(
    steps.find((step: { uses?: string }) => step.uses === "actions/checkout@v4")
      .with.ref,
  ).toBe("$" + "{{ github.event.pull_request.head.sha || github.sha }}");
  expect(
    steps.find(
      (step: { uses?: string }) => step.uses === "actions/upload-artifact@v4",
    ).with.path,
  ).toContain("workers/room-do-migrations/*.sql");
});
